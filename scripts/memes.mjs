// Save the blank template of every meme in memes/manifest.js as memes/img/<slug>.webp (at most 480x720),
// then write each image's size to memes/sizes.js so the page reserves its box before the image loads.
// Usage: npm run memes [-- --force]   (default: only memes with no image yet)
// Needs ImageMagick (`magick`) on PATH.
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const imgDir = path.join(root, 'memes', 'img');
const force = process.argv.includes('--force');

const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'memes', 'manifest.js'), 'utf8'), sandbox);
const memes = sandbox.window.POKAYOKE_MEMES ?? [];
fs.mkdirSync(imgDir, { recursive: true });

// imgflip serves a blank template at i.imgflip.com/<template id in base 36>.<jpg|png>.
async function download(id) {
  const key = Number(id).toString(36);
  for (const ext of ['jpg', 'png']) {
    const res = await fetch(`https://i.imgflip.com/${key}.${ext}`);
    if (res.ok && (res.headers.get('content-type') ?? '').startsWith('image/')) {
      return Buffer.from(await res.arrayBuffer());
    }
  }
  throw new Error(`imgflip has no image for template ${id}`);
}

let failed = false;
const sizes = {};
for (const meme of memes) {
  const out = path.join(imgDir, `${meme.slug}.webp`);
  try {
    // A format we built ourselves has no imgflip template: scripts/meme-formats.mjs makes its image.
    if (!meme.imgflip && !fs.existsSync(out)) throw new Error('no image yet: run npm run meme-formats');
    if (meme.imgflip && (force || !fs.existsSync(out))) {
      const source = await download(meme.imgflip);
      // `-` reads the download from stdin; `480x720>` only ever shrinks.
      execFileSync('magick', ['-', '-strip', '-resize', '480x720>', '-quality', '80', `webp:${out}`], { input: source });
      console.log(`saved  ${path.relative(root, out)}`);
    }
    const [w, h] = execFileSync('magick', ['identify', '-format', '%w %h', out], { encoding: 'utf8' }).split(' ').map(Number);
    sizes[meme.slug] = [w, h];
  } catch (err) {
    console.error(`${meme.id} ${meme.slug}: ${err.message}`);
    failed = true;
  }
}

const body = JSON.stringify(sizes, null, 2).replace(/\[\n\s+(\d+),\n\s+(\d+)\n\s+\]/g, '[$1, $2]');
fs.writeFileSync(
  path.join(root, 'memes', 'sizes.js'),
  `// Generated by scripts/memes.mjs: width and height of each memes/img/<slug>.webp.\nwindow.POKAYOKE_MEME_SIZES = ${body};\n`,
);
console.log(`${Object.keys(sizes).length} of ${memes.length} images sized`);
process.exit(failed ? 1 : 0);
